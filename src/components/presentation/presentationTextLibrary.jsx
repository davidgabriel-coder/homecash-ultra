const answerMatches = (answers, expectedAnswers) =>
  Object.entries(expectedAnswers).every(([questionId, optionId]) => answers[questionId]?.optionId === optionId);

export function getPresentationTextContent(questionnaireAnswers = {}) {
  const variant = TEXT_VARIANTS.find(({ answers }) => answerMatches(questionnaireAnswers, answers));

  if (!variant) {
    return DEFAULT_PRESENTATION_TEXT_CONTENT;
  }

  return {
    ...DEFAULT_PRESENTATION_TEXT_CONTENT,
    variantId: variant.id,
    ...variant.content
  };
}


const PUNCHLINE_VALUE_PATTERN = /([+]?\s*R\$\s*[\d.,]+(?:\s*(?:milh(?:\u00e3o|\u00f5es)|bilh(?:\u00e3o|\u00f5es)))?)/iu;

export const punchlineBoxTextClassName =
  'absolute left-[4.2%] top-[7.5%] flex h-[82%] w-[80%] flex-col justify-center gap-[0.2cqw] overflow-hidden text-[1.9cqw] leading-[1.12] tracking-[0] text-white';

export function renderPunchlineText(punchline) {
  if (typeof punchline !== 'string') return punchline;

  const match = punchline.match(PUNCHLINE_VALUE_PATTERN);
  if (!match?.index && match?.index !== 0) return punchline;

  const before = punchline.slice(0, match.index).trim();
  const value = match[0].trim();
  const after = punchline.slice(match.index + match[0].length).trim();

  return (
    <>
      {before ? <span className="block text-[1.55cqw] font-[500] leading-[0.98] opacity-90">{before}</span> : null}
      <span className="block max-w-full text-[3.02cqw] font-[900] leading-[0.82] tracking-[0] text-white drop-shadow-[0_0.12cqw_0_rgba(0,0,0,0.12)]">
        {value}
      </span>
      {after ? <span className="block text-[1.36cqw] font-[700] leading-[0.96] opacity-95">{after}</span> : null}
    </>
  );
}

export function renderThreeStepsTitle(title) {
  if (typeof title !== 'string') return title;

  const match = title.match(/3 etapas/i);
  if (!match?.index && match?.index !== 0) return title;

  const before = title.slice(0, match.index);
  const highlighted = match[0];
  const after = title.slice(match.index + match[0].length);
  const otherFlowBreak = ' para utilizar seu patrimônio ';

  if (after.includes(otherFlowBreak)) {
    const [lineStart, lineEnd] = after.split(otherFlowBreak);

    return (
      <>
        {before}
        <span className="font-[700] text-[#235ce9]">{highlighted}</span>
        {lineStart}
        {otherFlowBreak.trimEnd()}
        <br />
        {lineEnd}
      </>
    );
  }

  return (
    <>
      {before}
      <span className="font-[700] text-[#235ce9]">{highlighted}</span>
      {after}
    </>
  );
}
