const answerMatches = (answers, expectedAnswers) =>
  Object.entries(expectedAnswers).every(([questionId, optionId]) => answers?.[questionId]?.optionId === optionId);

export function getPlanoV2TextContent(questionnaireAnswers = {}) {
  const variant =
    PLANO_V2_TEXT_VARIANTS.find(({ answers }) => answerMatches(questionnaireAnswers, answers)) ??
    PLANO_V2_TEXT_VARIANTS.find(({ id }) => id === PLANO_V2_DEFAULT_VARIANT_ID);

  return { variantId: variant.id, fluxo: variant.fluxo, persona: variant.persona, ...variant.texts };
}

