// Primeiro nome do cliente (ex.: "Teresa Cristina Bordalo Santos" -> "Teresa"), usado no selo "No seu caso, {nome}".
export function getClientFirstName(name = '') {
  return String(name).trim().split(/\s+/).filter(Boolean)[0] ?? '';
}

// Iniciais do nome do cliente para o selo da capa e do encerramento (ex.: "Teresa Cristina Bordalo Santos" -> "TS").
export function getClientInitials(name = '') {
  const words = String(name).trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return '';
  const first = words[0][0];
  const last = words.length > 1 ? words[words.length - 1][0] : '';
  return `${first}${last}`.toUpperCase();
}
